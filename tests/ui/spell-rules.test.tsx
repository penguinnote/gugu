import { describe, expect, it } from "vitest";

import { fixSpelling } from "@/lib/spell/rules";

// 왼쪽 글 → 오른쪽 글. matchum 0.2.0 이 내는 답과 같아야 한다(옮긴 규칙이 그대로인지)
const SAME_AS_MATCHUM: [string, string][] = [
  ["몇일 뒤에 연락할께요. 나도 할수있다.", "며칠 뒤에 연락할게요. 나도 할 수 있다."],
  ["어케 됬어", "어케 됐어"],
  ["오랫만에 만나서 반가웠어요. 내일 연락할께요.", "오랜만에 만나서 반가웠어요. 내일 연락할게요."],
  ["함께 가요", "함께 가요"],
  ["할려고 했는데 먹을려면", "하려고 했는데 먹으려면"],
  ["않 된다", "안 된다"],
  ["하지 안았다", "하지 않았다"],
  ["왠 떡이야 왠지 좋아", "웬 떡이야 왠지 좋아"],
  ["하던지 말던지", "하든지 말든지"],
  ["책이예요 누구에요", "책이에요 누구예요"],
  ["했구요", "했고요"],
  ["감기가 낳았어요", "감기가 나았어요"],
  ["그렇게 되길 바래요", "그렇게 되길 바라요"],
  ["안하기로 했어요 불안하다 미안해요", "안 하기로 했어요 불안하다 미안해요"],
  ["너때문에", "너 때문에"],
  ["할수밖에 없다 할 수 밖에", "할 수밖에 없다 할 수밖에"],
  ["하는게 좋아 하는거야", "하는 게 좋아 하는 거야"],
  ["할텐데 그럴리가 없다", "할 텐데 그럴 리가 없다"],
  ["닥치는대로 앉은채로", "닥치는 대로 앉은 채로"],
  ["하지않다 하지마 새옹지마", "하지 않다 하지 마 새옹지마"],
  ["보고싶다 하고있다", "보고 싶다 하고 있다"],
  ["친구 처럼 집에서 부터", "친구처럼 집에서부터"],
  ["그런게 있어", "그런 게 있어"],
  ["떨지않고 잘 할께요", "떨지 않고 잘 할게요"],
  ["회복됬으면 좋겠어요", "회복됐으면 좋겠어요"],
  ["설겆이 하고 일찍이", "설거지 하고 일찍이"],
  ["시험 잘볼수있도록", "시험 잘볼 수 있도록"],
];

describe("규칙으로 맞춤법 고치기", () => {
  it.each(SAME_AS_MATCHUM)("%s → %s", (from, to) => {
    expect(fixSpelling(from)).toBe(to);
  });

  it("두 번 돌려 옆자리 규칙도 잡는다 · 줄바꿈은 그대로", () => {
    expect(fixSpelling("할것같다\n갈때 할줄 알아")).toBe("할 것 같다\n갈 때 할 줄 알아");
  });

  it("보고서에서 자주 보이는 것", () => {
    expect(fixSpelling("이번주 이직 고민중인데 하나님 뜻을 구하길 원함니다")).toBe("이번 주 이직 고민 중인데 하나님 뜻을 구하길 원합니다");
    expect(fixSpelling("조급해지지 않토록 한주 동안 집중인데")).toBe("조급해지지 않도록 한 주 동안 집중인데");
  });

  it("맞는 글은 건드리지 않는다", () => {
    const ok = "시험을 잘 볼 수 있도록, 가족이 건강하도록 기도해 주세요. 며칠 뒤에 면접이 있어요.";
    expect(fixSpelling(ok)).toBe(ok);
  });
});
